export type Lang = 'ko' | 'en';
const STORE = 'shopfloor-replay:lang';
function initial(): Lang {
  try { const saved = localStorage.getItem(STORE); if (saved === 'ko' || saved === 'en') return saved; } catch { /* storage blocked */ }
  return navigator.language.toLowerCase().startsWith('ko') ? 'ko' : 'en';
}
export let lang: Lang = initial();
export function setLang(next: Lang): void {
  lang = next;
  try { localStorage.setItem(STORE, next); } catch { /* storage blocked */ }
}
export function t(key: Key, params: Record<string, string | number> = {}): string {
  return (lang === 'ko' ? ko : en)[key].replace(/\{(\w+)\}/g, (all, name: string) => name in params ? String(params[name]) : all);
}
export const has = (key: string): key is Key => key in ko;
const locale = () => (lang === 'ko' ? 'ko-KR' : 'en-US');
export const num = (n: number, digits = 0) => n.toLocaleString(locale(), { minimumFractionDigits: digits, maximumFractionDigits: digits });
export const pct = (rate: number | null) => rate === null ? t('pending') : num(rate * 100, 1) + '%';
export const when = (iso: string) => new Date(iso).toLocaleString(locale(), { timeZone: 'Asia/Seoul', dateStyle: 'medium', timeStyle: 'short' }) + ' KST';
